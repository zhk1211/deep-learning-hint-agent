#!/usr/bin/env python3
# -*- coding: utf-8 -*-

"""
Analyze hint-evaluation results and draw statistics figures.

Input format:
    CF1798C 111111 01010
    CF1792D 0011111 10111
    CF1776F

A line without the first bit string means the problem is not in the evaluated set
and will be skipped.

First bit-string convention:
    first bit    = statement only / 0 Hint
    middle bits  = first k hints generated by version 1
    last bit     = official solution/editorial condition

Second bit-string convention:
    another version's generated-hint results. By default, the script uses
    --second_bits_format auto:
        1. If len(second_bits) == len(first_bits), treat it as full format:
           0 Hint + generated hints + Solution, but replace 0 Hint with
           first_bits[0] and exclude the final Solution bit.
        2. If len(second_bits) == len(first_bits) - 1, treat it as hint-process
           format: 0 Hint + generated hints, but replace 0 Hint with first_bits[0].
        3. Otherwise, treat it as generated-hints-only format and prepend
           first_bits[0] as the common 0 Hint result.

Important:
    percentage_accuracy_curve.png analyzes the hint process:
        0 Hint -> 1 Hint -> ... -> All Hints

    The official-solution bit from the first string is NOT included in the
    normalized hint curve. It is plotted as a separate point on the right.

    Version 1 is plotted with the default matplotlib color.
    Version 2 is plotted as an orange line.
"""

