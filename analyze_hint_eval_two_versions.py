PROBLEM_ID_RE = re.compile(r"\bCF\s*(\d+)\s*([A-Za-z])([0-9]*)\b")
BIT_RE = re.compile(r"[01]+")


SECOND_BITS_FORMATS = {"auto", "generated_hints", "hint_process", "full"}


def normalize_problem_id(pid: str) -> str:
    """Normalize problem ids such as cf2219b1 / CF 2219 B1 to CF2219B1."""
    match = PROBLEM_ID_RE.search(pid)
    if not match:
        return pid.strip().upper()
    contest_id, index_letter, index_suffix = match.groups()
    return f"CF{contest_id}{index_letter.upper()}{index_suffix}"


def collect_with_hint_problem_ids(with_hint_dir: Path) -> Set[str]:
    """Collect problem ids that already appear under cf_scraper/cf_dataset/with_hint."""
    problem_ids: Set[str] = set()

    if not with_hint_dir.exists():
        return problem_ids

    for path in with_hint_dir.rglob("*"):
        if not path.is_file():
            continue

        match = PROBLEM_ID_RE.search(path.stem)
        if match:
            problem_ids.add(normalize_problem_id(match.group(0)))

    return problem_ids


def skip_records_existing_in_with_hint(records: List[Dict], existing_problem_ids: Set[str]) -> Tuple[List[Dict], List[str]]:
    """Remove evaluation records whose problem id has already appeared in with_hint."""
    if not existing_problem_ids:
        return records, []

    kept_records: List[Dict] = []
    skipped_existing: List[str] = []

    for rec in records:
        problem_id = normalize_problem_id(rec["problem"])
        if problem_id in existing_problem_ids:
            skipped_existing.append(rec["problem"])
        else:
            kept_records.append(rec)

    return kept_records, skipped_existing


def build_second_hint_bits(first_bits: str, second_bits: str, second_bits_format: str) -> Tuple[str, str]:
    """
    Convert the second bit string into a hint-process string.

    The returned hint-process string always starts with first_bits[0], because
    0 Hint / statement-only should be shared by both versions.
    """
    if second_bits_format not in SECOND_BITS_FORMATS:
        raise ValueError(f"Unknown second_bits_format: {second_bits_format}")

    no_hint_bit = first_bits[0]

    if second_bits_format == "full":
        # second_bits = 0 Hint + generated hints + Solution.
        # Use the first string's 0 Hint and remove second string's final Solution.
        if len(second_bits) < 2:
            raise ValueError("full second bit string must contain at least 2 bits")
        return no_hint_bit + second_bits[1:-1], "full"

    if second_bits_format == "hint_process":
        # second_bits = 0 Hint + generated hints, without Solution.
        # Replace its 0 Hint by the first string's 0 Hint.
        if len(second_bits) < 1:
            raise ValueError("hint_process second bit string must contain at least 1 bit")
        return no_hint_bit + second_bits[1:], "hint_process"

    if second_bits_format == "generated_hints":
        # second_bits = generated hints only, without 0 Hint and without Solution.
        return no_hint_bit + second_bits, "generated_hints"

    # auto mode:
    # 1. Same length as first full string: assume full format.
    # 2. One shorter than first full string: assume hint process format.
    # 3. Otherwise: assume generated-hints-only format.
    if len(second_bits) == len(first_bits):
        return no_hint_bit + second_bits[1:-1], "full"
    if len(second_bits) == len(first_bits) - 1:
        return no_hint_bit + second_bits[1:], "hint_process"
    return no_hint_bit + second_bits, "generated_hints"


def parse_data(text: str, second_bits_format: str = "auto") -> Tuple[List[Dict], List[str], List[str]]:
    records: List[Dict] = []
    skipped: List[str] = []
    bad_lines: List[str] = []

    for raw_line in text.splitlines():
        line = raw_line.strip()
        if not line:
            continue

        parts = line.split()
        pid = parts[0]
        bits = parts[1] if len(parts) >= 2 else ""
        second_bits: Optional[str] = parts[2] if len(parts) >= 3 else None

        if len(parts) > 3:
            bad_lines.append(raw_line)
            continue

        if not bits:
            skipped.append(pid)
            continue

        if not BIT_RE.fullmatch(bits):
            bad_lines.append(raw_line)
            continue

        if len(bits) < 2:
            bad_lines.append(raw_line)
            continue

        if second_bits is not None and not BIT_RE.fullmatch(second_bits):
            bad_lines.append(raw_line)
            continue

        hint_bits = bits[:-1]
        solution_bit = bits[-1]

        second_hint_bits = ""
        detected_second_bits_format = ""
        if second_bits:
            try:
                second_hint_bits, detected_second_bits_format = build_second_hint_bits(
                    bits,
                    second_bits,
                    second_bits_format,
                )
            except ValueError:
                bad_lines.append(raw_line)
                continue

        rec = {
            "problem": pid,
            "bits": bits,
            "second_bits": second_bits or "",
            "detected_second_bits_format": detected_second_bits_format,
            "hint_bits": hint_bits,
            "second_hint_bits": second_hint_bits,
            "length": len(bits),
            "second_length": len(second_bits) if second_bits else 0,
            "hint_length": len(hint_bits),
            "second_hint_length": len(second_hint_bits),
            "num_hints": max(0, len(bits) - 2),
            "second_num_hints": max(0, len(second_hint_bits) - 1) if second_hint_bits else 0,
            "has_second_bits": bool(second_hint_bits),
            "no_hint": int(bits[0]),
            "all_hints": int(hint_bits[-1]),
            "second_all_hints": int(second_hint_bits[-1]) if second_hint_bits else "",
            "solution": int(solution_bit),
        }
        records.append(rec)

    return records, skipped, bad_lines


def write_csv(path: Path, rows: List[Dict]) -> None:
    if not rows:
        path.write_text("", encoding="utf-8")
        return

    fieldnames = list(rows[0].keys())
    with path.open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)


def percentage_bins(records: List[Dict], bins: int = 20, hint_key: str = "hint_bits") -> List[Dict]:
    """
    Aggregate a hint-process bit string onto fixed percentage bins.

    For a hint-process string of length H, bit i occupies [i/H, (i+1)/H).
    The official-solution bit is deliberately excluded before this function is called.
    """
    rows: List[Dict] = []

    for b in range(bins):
        bin_l = b / bins
        bin_r = (b + 1) / bins

        weighted_success = 0.0
        total_weight = 0.0
        contributing = set()

        for rec in records:
            hint_bits = rec.get(hint_key, "")
            H = len(hint_bits)
            if H == 0:
                continue

            for i, ch in enumerate(hint_bits):
                seg_l = i / H
                seg_r = (i + 1) / H
                overlap = max(0.0, min(bin_r, seg_r) - max(bin_l, seg_l))
                if overlap <= 0:
                    continue

                weighted_success += int(ch) * overlap
                total_weight += overlap
                contributing.add(rec["problem"])

        rows.append({
            "bin": b,
            "percent_left": bin_l * 100,
            "percent_right": bin_r * 100,
            "percent_mid": (bin_l + bin_r) * 50,
            "accuracy": weighted_success / total_weight if total_weight > 0 else float("nan"),
            "contributing_problems": len(contributing),
            "total_weight": total_weight,
        })

    return rows


def add_version_to_rows(rows: List[Dict], version: str) -> List[Dict]:
    return [{"version": version, **row} for row in rows]


def stage_summary(records: List[Dict]) -> List[Dict]:
    rows: List[Dict] = []
    total = len(records)

    def add_row(stage: str, correct: int, stage_total: int) -> None:
        rows.append({
            "stage": stage,
            "correct": correct,
            "total": stage_total,
            "accuracy": correct / stage_total if stage_total > 0 else float("nan"),
        })

    add_row(
        "0 Hint / statement only",
        sum(int(r["no_hint"]) for r in records),
        total,
    )
    add_row(
        "All generated hints (version 1)",
        sum(int(r["all_hints"]) for r in records),
        total,
    )

    second_records = [r for r in records if r.get("second_hint_bits")]
    if second_records:
        add_row(
            "All generated hints (version 2)",
            sum(int(r["second_all_hints"]) for r in second_records),
            len(second_records),
        )

    add_row(
        "Official solution/editorial",
        sum(int(r["solution"]) for r in records),
        total,
    )

    return rows


def length_summary(records: List[Dict], length_key: str = "length") -> List[Dict]:
    cnt: Dict[int, int] = {}
    for r in records:
        length = int(r.get(length_key, 0) or 0)
        if length <= 0:
            continue
        cnt[length] = cnt.get(length, 0) + 1

    return [{"length": k, "count": cnt[k]} for k in sorted(cnt)]


def plot_percentage_curve(
    bin_rows_v1: List[Dict],
    bin_rows_v2: List[Dict],
    stage_rows: List[Dict],
    out_path: Path,
) -> None:
    xs_v1 = [r["percent_mid"] for r in bin_rows_v1]
    ys_v1 = [r["accuracy"] * 100 for r in bin_rows_v1]

    xs_v2 = [r["percent_mid"] for r in bin_rows_v2 if r["total_weight"] > 0]
    ys_v2 = [r["accuracy"] * 100 for r in bin_rows_v2 if r["total_weight"] > 0]

    solution_acc = None
    for r in stage_rows:
        if r["stage"] == "Official solution/editorial":
            solution_acc = r["accuracy"] * 100

    plt.figure(figsize=(9.5, 5.2))
    plt.plot(xs_v1, ys_v1, marker="o", label="Hint process (version 1)")

    if xs_v2:
        plt.plot(xs_v2, ys_v2, marker="o", color="orange", label="Hint process (version 2)")

    if solution_acc is not None:
        solution_x = 110
        plt.scatter([solution_x], [solution_acc], marker="*", s=180, label="Official solution")
        plt.axvline(100, linestyle="--", linewidth=1, alpha=0.5)
        plt.text(solution_x, solution_acc + 2, "Solution", ha="center", va="bottom")

    plt.xlabel("Normalized hint progress: 0 Hint → All Hints (%)")
    plt.ylabel("Accuracy (%)")
    plt.title("Accuracy by normalized hint progress")
    plt.ylim(35, 85)
    plt.xlim(0, 115)
    plt.grid(True, alpha=0.3)
    plt.legend()
    plt.tight_layout()
    plt.savefig(out_path, dpi=200)
    plt.close()


def plot_stage_bar(stage_rows: List[Dict], out_path: Path) -> None:
    labels = [r["stage"] for r in stage_rows]
    values = [r["accuracy"] * 100 for r in stage_rows]

    plt.figure(figsize=(9.5, 5))
    plt.bar(labels, values)
    plt.ylabel("Accuracy (%)")
    plt.title("Accuracy at key conditions")
    plt.ylim(0, 100)
    plt.xticks(rotation=15, ha="right")
    plt.tight_layout()
    plt.savefig(out_path, dpi=200)
    plt.close()


def plot_length_distribution(len_rows: List[Dict], out_path: Path, title: str) -> None:
    labels = [str(r["length"]) for r in len_rows]
    values = [r["count"] for r in len_rows]

    plt.figure(figsize=(8, 5))
    plt.bar(labels, values)
    plt.xlabel("Bit-string length")
    plt.ylabel("Number of problems")
    plt.title(title)
    plt.tight_layout()
    plt.savefig(out_path, dpi=200)
    plt.close()


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", type=str, default=None, help="Input txt file. If omitted, use SAMPLE_DATA in script.")
    parser.add_argument("--output_dir", type=str, default="hint_eval_analysis")
    parser.add_argument("--bins", type=int, default=20, help="Number of percentage bins; 20 means 5% per bin.")
    parser.add_argument(
        "--dataset_dir",
        type=str,
        default="cf_scraper/cf_dataset",
        help="Dataset root directory. Used to find the with_hint folder.",
    )
    parser.add_argument(
        "--with_hint_dir",
        type=str,
        default=None,
        help="Existing with_hint directory. If omitted, use <dataset_dir>/with_hint.",
    )
    parser.add_argument(
        "--second_bits_format",
        choices=sorted(SECOND_BITS_FORMATS),
        default="auto",
        help=(
            "How to interpret the second 01 string. "
            "auto: infer by length; generated_hints: generated hints only; "
            "hint_process: 0 Hint + generated hints; full: 0 Hint + generated hints + Solution."
        ),
    )
    args = parser.parse_args()

    if args.input:
        text = Path(args.input).read_text(encoding="utf-8")
    else:
        text = SAMPLE_DATA

    out_dir = Path(args.output_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    records, skipped, bad_lines = parse_data(text, second_bits_format=args.second_bits_format)

    dataset_dir = Path(args.dataset_dir)
    with_hint_dir = Path(args.with_hint_dir) if args.with_hint_dir else dataset_dir / "with_hint"
    existing_with_hint_problem_ids = collect_with_hint_problem_ids(with_hint_dir)
    records, skipped_existing_with_hint = skip_records_existing_in_with_hint(records, existing_with_hint_problem_ids)

    bin_rows_v1 = percentage_bins(records, bins=args.bins, hint_key="hint_bits")
    bin_rows_v2 = percentage_bins(records, bins=args.bins, hint_key="second_hint_bits")
    bin_rows_combined = add_version_to_rows(bin_rows_v1, "version_1") + add_version_to_rows(bin_rows_v2, "version_2")

    stage_rows = stage_summary(records)
    len_rows_v1 = length_summary(records, length_key="length")
    len_rows_v2 = length_summary(records, length_key="second_length")

    write_csv(out_dir / "parsed_records.csv", records)
    write_csv(out_dir / "percentage_bins_hint_only_v1.csv", bin_rows_v1)
    write_csv(out_dir / "percentage_bins_hint_only_v2.csv", bin_rows_v2)
    write_csv(out_dir / "percentage_bins_hint_only_both_versions.csv", bin_rows_combined)
    write_csv(out_dir / "stage_summary.csv", stage_rows)
    write_csv(out_dir / "length_summary_v1.csv", len_rows_v1)
    write_csv(out_dir / "length_summary_v2.csv", len_rows_v2)

    (out_dir / "skipped_problems.txt").write_text("\n".join(skipped) + ("\n" if skipped else ""), encoding="utf-8")
    (out_dir / "skipped_existing_with_hint.txt").write_text(
        "\n".join(skipped_existing_with_hint) + ("\n" if skipped_existing_with_hint else ""),
        encoding="utf-8",
    )
    (out_dir / "bad_lines.txt").write_text("\n".join(bad_lines) + ("\n" if bad_lines else ""), encoding="utf-8")

    plot_percentage_curve(bin_rows_v1, bin_rows_v2, stage_rows, out_dir / "percentage_accuracy_curve.png")
    plot_stage_bar(stage_rows, out_dir / "stage_accuracy_bar.png")
    plot_length_distribution(len_rows_v1, out_dir / "length_distribution_v1.png", "Distribution of first bit-string lengths")
    if len_rows_v2:
        plot_length_distribution(len_rows_v2, out_dir / "length_distribution_v2.png", "Distribution of second bit-string lengths")

    def find_acc(stage_name: str):
        for r in stage_rows:
            if r["stage"] == stage_name:
                return r["accuracy"]
        return None

    records_with_second = [r for r in records if r.get("second_hint_bits")]
    detected_second_formats: Dict[str, int] = {}
    for r in records_with_second:
        fmt = str(r.get("detected_second_bits_format", ""))
        detected_second_formats[fmt] = detected_second_formats.get(fmt, 0) + 1

    summary = {
        "evaluated_problems": len(records),
        "evaluated_problems_with_second_bits": len(records_with_second),
        "skipped_problems": len(skipped),
        "skipped_existing_with_hint": len(skipped_existing_with_hint),
        "bad_lines": len(bad_lines),
        "bins": args.bins,
        "dataset_dir": str(dataset_dir),
        "with_hint_dir": str(with_hint_dir),
        "existing_with_hint_problems": len(existing_with_hint_problem_ids),
        "second_bits_format_argument": args.second_bits_format,
        "detected_second_bits_formats": detected_second_formats,
        "percentage_curve": "two hint-process curves; version 2 is orange; official solution is plotted separately on the right",
        "no_hint_accuracy": find_acc("0 Hint / statement only"),
        "all_hints_accuracy_v1": find_acc("All generated hints (version 1)"),
        "all_hints_accuracy_v2": find_acc("All generated hints (version 2)"),
        "solution_accuracy": find_acc("Official solution/editorial"),
    }

    (out_dir / "summary.json").write_text(json.dumps(summary, ensure_ascii=False, indent=2), encoding="utf-8")

    print("Done.")
    print(f"Evaluated problems: {len(records)}")
    print(f"Evaluated problems with second bit string: {len(records_with_second)}")
    print(f"Skipped problems: {len(skipped)}")
    print(f"Skipped existing with_hint problems: {len(skipped_existing_with_hint)}")
    print(f"Existing problems found in {with_hint_dir}: {len(existing_with_hint_problem_ids)}")
    print(f"Bad lines: {len(bad_lines)}")
    if detected_second_formats:
        print("Detected second bit-string formats:")
        for fmt, cnt in sorted(detected_second_formats.items()):
            print(f"  {fmt}: {cnt}")
    print("\nStage summary:")
    for r in stage_rows:
        print(f"{r['stage']}: {r['correct']}/{r['total']} = {r['accuracy']:.2%}")
    print(f"\nOutputs written to: {out_dir.resolve()}")


if __name__ == "__main__":
    main()
